/**
 * Skill Compression Matrix Integrity
 *
 * Guards the INPUTS of the skill-compression eval, not its run. A harness that
 * executes cleanly against a degenerate matrix produces confident, wrong
 * numbers: if `summarized/<skill>.md` is a byte-for-byte copy of
 * `baseline/<skill>.md`, the summarized arm scores identically to baseline and
 * that reads as "compression is free" when it only means "the files are the
 * same bytes."
 *
 * The matrix is 4 variants x 3 skills = 12 cells. Every cell is a variant of a
 * SKILL.md *prompt*. The eval then runs each prompt against its scenario and
 * scores the resulting output at outputs/<variant>/<skill>/output.md.
 *
 * Invariants asserted here:
 *   1. All 12 cells exist.
 *   2. No two cells within the same skill are byte-identical.
 *   3. Size ordering (line count): conservative < baseline, summarized <
 *      baseline, aggressive < summarized.
 *   4. The runner's outputs/ path shape is documented and matches run-eval.mjs.
 *   5. Rubric floor: every required element that baseline's prompt matches must
 *      also be matched by every compressed variant of that skill. This is the
 *      check that separates "compression cost quality" from "the variant author
 *      dropped a load-bearing instruction."
 *
 * Usage:
 *   node --test tests/evals/skill-compression/matrix-integrity.test.mjs
 */

import { describe, it } from "node:test";
import assert from "node:assert/strict";
import { readFileSync, existsSync, readdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(__dirname, "..", "..", "..");
const VARIANTS_DIR = join(__dirname, "variants");
const RUBRICS_DIR = join(__dirname, "rubrics");

/** Compression tiers, ordered most verbose to most compressed. */
const VARIANTS = ["baseline", "conservative", "summarized", "aggressive"];
const SKILLS = ["brainstorm", "specify", "plan"];
const COMPRESSED = VARIANTS.filter(v => v !== "baseline");

/**
 * Size ordering the matrix must satisfy, expressed as [smaller, larger] pairs
 * compared by line count.
 *
 * Note there is deliberately NO conservative-vs-summarized assertion. They
 * compress along different axes: `conservative` trims prose while keeping every
 * section, whereas `summarized` condenses the body AND adds an artifact-to-disk
 * output directive (write the full artifact to disk, present only a summary).
 * The directive costs prompt lines in order to save conversation tokens, so
 * summarized can legitimately land above or below conservative. Both must be
 * under baseline, and aggressive must be under summarized.
 */
const SIZE_ORDER = [
  ["conservative", "baseline"],
  ["summarized", "baseline"],
  ["aggressive", "summarized"],
];

/**
 * Path template run-eval.mjs globs for scored outputs, relative to this
 * directory. outputs/ is generated by capturing each scenario run per variant
 * and is gitignored, so it is absent on a clean checkout. That absence is not a
 * matrix defect: the runner reports missing outputs and exits 0.
 */
const OUTPUT_PATH_TEMPLATE = "outputs/<variant>/<skill>/output.md";

function cellPath(variant, skill) {
  return join(VARIANTS_DIR, variant, `${skill}.md`);
}

/** Returns file text, or null when the cell is absent. */
function readCell(variant, skill) {
  const path = cellPath(variant, skill);
  return existsSync(path) ? readFileSync(path, "utf-8") : null;
}

function md5(text) {
  return createHash("md5").update(text).digest("hex");
}

function lineCount(text) {
  return text.split("\n").length - (text.endsWith("\n") ? 1 : 0);
}

/** Human-readable "216 lines (md5 04e2fee9...)" for failure messages. */
function describeCell(text) {
  return `${lineCount(text)} lines (md5 ${md5(text)})`;
}

/** Minimal extractor for the rubric's `required_elements` list. */
function parseRequiredElements(skill) {
  const lines = readFileSync(join(RUBRICS_DIR, `${skill}.yaml`), "utf-8").split("\n");
  const elements = [];
  let current = null;
  let inSection = false;

  for (const line of lines) {
    if (line.startsWith("required_elements:")) {
      inSection = true;
      continue;
    }
    if (/^\w/.exec(line)) inSection = false;
    if (!inSection) continue;

    const item = /^ {2}- id:\s*(.*)/.exec(line);
    if (item) {
      current = { id: item[1].trim() };
      elements.push(current);
      continue;
    }
    const prop = /^ {4}(\w+):\s*(.*)/.exec(line);
    if (prop && current) {
      let value = prop[2].trim();
      if (value.startsWith('"') && value.endsWith('"')) {
        value = value.slice(1, -1).replace(/\\\\/g, "\\");
      }
      current[prop[1]] = value;
    }
  }
  return elements;
}

/** Compiles a rubric pattern, returning null when the rubric itself is malformed. */
function compilePattern(pattern) {
  try {
    return new RegExp(pattern, "im");
  } catch {
    return null;
  }
}

function matches(re, text) {
  return re.exec(text) !== null;
}

describe("skill-compression matrix integrity", () => {
  describe("1. every cell exists", () => {
    for (const skill of SKILLS) {
      for (const variant of VARIANTS) {
        it(`${variant}/${skill}.md exists`, () => {
          assert.ok(
            existsSync(cellPath(variant, skill)),
            `Missing matrix cell variants/${variant}/${skill}.md. The matrix is ` +
              `${VARIANTS.length} variants x ${SKILLS.length} skills = ` +
              `${VARIANTS.length * SKILLS.length} cells; a missing cell silently drops an arm.`,
          );
        });
      }
    }

    it("has no variant directory beyond the declared tiers", () => {
      // run-eval.mjs globs whatever directories exist under variants/, so a new
      // tier added later would be scored while every check below still passed.
      const onDisk = readdirSync(VARIANTS_DIR, { withFileTypes: true })
        .filter(entry => entry.isDirectory())
        .map(entry => entry.name)
        .sort();
      assert.deepEqual(
        onDisk,
        [...VARIANTS].sort(),
        `variants/ directories drifted from the declared tiers. run-eval.mjs scores ` +
          `every directory it finds, so add the new tier to VARIANTS (and to SIZE_ORDER) ` +
          `or remove the directory.`,
      );
    });
  });

  describe("2. no two cells within a skill are byte-identical", () => {
    for (const skill of SKILLS) {
      it(`${skill}: all variants are distinct`, () => {
        const byDigest = new Map();
        const duplicates = [];

        for (const variant of VARIANTS) {
          const text = readCell(variant, skill);
          if (text === null) continue; // absence is reported by check 1
          const digest = md5(text);
          const twin = byDigest.get(digest);
          duplicates.push(
            ...(twin === undefined
              ? []
              : [`${variant}/${skill}.md == ${twin}/${skill}.md [${describeCell(text)}]`]),
          );
          byDigest.set(digest, twin ?? variant);
        }

        assert.deepEqual(
          duplicates,
          [],
          `BYTE-IDENTICAL matrix cells found for ${skill}: ${duplicates.join("; ")}. ` +
            `Identical cells make two arms score the same for a reason that has nothing ` +
            `to do with compression quality.`,
        );
      });
    }
  });

  describe("3. size ordering by line count", () => {
    for (const skill of SKILLS) {
      for (const [smaller, larger] of SIZE_ORDER) {
        it(`${skill}: ${smaller} < ${larger}`, () => {
          const smallText = readCell(smaller, skill);
          const largeText = readCell(larger, skill);

          assert.notEqual(
            smallText,
            null,
            `Cannot compare sizes: variants/${smaller}/${skill}.md is missing.`,
          );
          assert.notEqual(
            largeText,
            null,
            `Cannot compare sizes: variants/${larger}/${skill}.md is missing.`,
          );

          const smallLines = lineCount(smallText);
          const largeLines = lineCount(largeText);

          assert.ok(
            smallLines < largeLines,
            `variants/${smaller}/${skill}.md must be smaller than ` +
              `variants/${larger}/${skill}.md, but got ` +
              `${smaller}=${describeCell(smallText)} vs ${larger}=${describeCell(largeText)}. ` +
              `A "compressed" variant that is not smaller is not a compression.`,
          );
        });
      }
    }
  });

  describe("4. runner output path shape", () => {
    it("matches the outputs/ path run-eval.mjs builds", () => {
      const runner = readFileSync(join(__dirname, "run-eval.mjs"), "utf-8");

      assert.match(
        runner,
        /const OUTPUTS_DIR = join\(__dirname, ['"]outputs['"]\)/,
        "run-eval.mjs no longer roots scored outputs at <this dir>/outputs.",
      );
      assert.match(
        runner,
        /join\(\s*OUTPUTS_DIR\s*,\s*variant\s*,\s*skill\s*,\s*['"]output\.md['"]\s*\)/,
        `run-eval.mjs no longer builds output paths as ${OUTPUT_PATH_TEMPLATE}; ` +
          `update OUTPUT_PATH_TEMPLATE in this test to match.`,
      );
      assert.equal(
        OUTPUT_PATH_TEMPLATE,
        "outputs/<variant>/<skill>/output.md",
        "OUTPUT_PATH_TEMPLATE drifted from the documented shape.",
      );
    });

    it("keeps outputs/ generated rather than committed", () => {
      const gitignore = readFileSync(join(REPO_ROOT, ".gitignore"), "utf-8");
      assert.ok(
        gitignore.includes("tests/evals/skill-compression/outputs/"),
        `outputs/ must stay gitignored: it is regenerated by capturing each scenario ` +
          `run per variant (${OUTPUT_PATH_TEMPLATE}), so a clean checkout has no outputs/ ` +
          `and run-eval.mjs reports that as informational rather than as a failure.`,
      );
    });
  });

  describe("5. rubric floor: compressed variants keep what baseline matches", () => {
    for (const skill of SKILLS) {
      const elements = parseRequiredElements(skill);

      it(`${skill}: rubric declares required elements`, () => {
        assert.ok(elements.length > 0, `rubrics/${skill}.yaml has no required_elements`);
      });

      for (const variant of COMPRESSED) {
        it(`${skill}: ${variant} retains every element baseline matches`, () => {
          const baselineText = readCell("baseline", skill);
          const variantText = readCell(variant, skill);

          assert.notEqual(baselineText, null, `variants/baseline/${skill}.md is missing.`);
          assert.notEqual(
            variantText,
            null,
            `variants/${variant}/${skill}.md is missing — cannot check the rubric floor.`,
          );

          // Only elements the baseline PROMPT itself matches form the floor. Some
          // rubric patterns are scenario-specific (they target the produced output,
          // not the prompt) and match no variant, including baseline.
          const floor = elements
            .map(el => ({ id: el.id, re: compilePattern(el.match_pattern) }))
            .filter(el => el.re !== null)
            .filter(el => matches(el.re, baselineText));

          const dropped = floor.filter(el => !matches(el.re, variantText)).map(el => el.id);

          assert.deepEqual(
            dropped,
            [],
            `variants/${variant}/${skill}.md dropped required element(s) that ` +
              `variants/baseline/${skill}.md carries: ${dropped.join(", ")}. ` +
              `A compressed variant missing a load-bearing instruction makes the eval ` +
              `report an authoring bug as a quality cost of compression.`,
          );
        });
      }
    }
  });
});
