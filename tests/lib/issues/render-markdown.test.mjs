/**
 * Tests for lib/issues/render-markdown.mjs (markdown-rendering-layer spec).
 *
 * Covers:
 *   - Task 1: skeleton + GENERATED_HEADER constant
 *   - Task 2: renderTasksMd(board) body with epics + open + closed sections
 *   - Task 3: writeTasksMd(projectRoot) I/O wrapper, atomic write, CON-5, CON-6
 *   - Task 7: path-containment defenses (INVALID_PROJECT_ROOT / INVALID_STORAGE_PATH)
 *   - Task 9: SEC-1 — `-->` stripped from source interpolation
 *   - Task 17: rendered-file-editing-has-no-effect invariant
 */

import { describe, it, beforeEach, afterEach } from "node:test";
import assert from "node:assert/strict";
import { existsSync, mkdirSync, readFileSync, writeFileSync, symlinkSync, statSync } from "node:fs";
import { join } from "node:path";

import {
  renderTasksMd,
  writeTasksMd,
  GENERATED_HEADER,
} from "../../../lib/issues/render-markdown.mjs";
import { JsonAdapter } from "../../../lib/issues/json-adapter.mjs";
import { parseTasksMd } from "../../../lib/issues/markdown-parser.mjs";
import { createTempDir, cleanupTempDir, writeFixture } from "../../helpers.mjs";

function seedProject(tmp) {
  // Minimal manifest required by JsonAdapter / writeTasksMd.
  writeFixture(tmp, ".context-index/manifest.yaml", "project:\n  name: render-test\n");
  return tmp;
}

describe("renderTasksMd / writeTasksMd — Task 1 skeleton", () => {
  it("exposes renderTasksMd and writeTasksMd as functions", () => {
    assert.equal(typeof renderTasksMd, "function");
    assert.equal(typeof writeTasksMd, "function");
  });

  it("exports GENERATED_HEADER as a callable header builder", () => {
    // Callable form `GENERATED_HEADER(source)` returns the canonical comment.
    assert.equal(typeof GENERATED_HEADER, "function");
    const out = GENERATED_HEADER("tasks.json");
    assert.ok(out.startsWith("<!--") && out.endsWith("-->"));
    assert.ok(out.includes("DO NOT EDIT"));
    assert.ok(out.includes("tasks.json"));
  });

  it("GENERATED_HEADER is a function that returns the canonical comment template with the source slot", () => {
    // Per spec: `<!-- DO NOT EDIT — generated by \`adev status --render\` from <source>. Edits will be lost on next regeneration. -->`
    // We accept either:
    //   - a function GENERATED_HEADER(source) -> string interpolating the source, OR
    //   - a literal string containing the placeholder token "${source}" — but a callable
    //     is preferred because rendering needs source substitution.
    // The minimal contract: passing a source value through the public renderTasksMd
    // produces output containing the literal "DO NOT EDIT" marker and the source ref.
    const board = { version: 2, epics: [], issues: [] };
    const rendered = renderTasksMd(board);
    assert.ok(
      rendered.includes("DO NOT EDIT"),
      "rendered output must contain the DO NOT EDIT marker",
    );
    assert.ok(
      rendered.includes("tasks.json"),
      "rendered tasks.md must reference its source as tasks.json",
    );
  });
});

