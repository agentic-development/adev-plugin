// ─── Task 3: writeTasksMd I/O wrapper ──────────────────────────────────────

describe("writeTasksMd — Task 3 atomic write + CON-5 + CON-6", () => {
  let tmp;
  beforeEach(() => {
    tmp = seedProject(createTempDir());
  });
  afterEach(() => cleanupTempDir(tmp));

  it("writes <storageRoot>/.context-index/tasks/tasks.md from JsonAdapter list+listEpics", async () => {
    const adapter = new JsonAdapter(tmp);
    await adapter.init();
    await adapter.create({ title: "T1", type: "task", priority: 2 });
    await writeTasksMd(tmp);
    const out = join(tmp, ".context-index", "tasks", "tasks.md");
    assert.ok(existsSync(out), "tasks.md must exist");
    const text = readFileSync(out, "utf8");
    assert.ok(text.includes("DO NOT EDIT"), "must include generated-header");
    assert.ok(text.includes("T1"), "rendered tasks.md must include issue title");
  });

  it("CON-5: throws INVALID_STORAGE_PATH when storage root is not a directory", async () => {
    // Construct a project where tasks.db_path points to a file, not a dir.
    const projDir = createTempDir();
    try {
      writeFixture(projDir, ".context-index/manifest.yaml", "");
      const fakeFile = join(projDir, "not-a-dir");
      writeFileSync(fakeFile, "");
      writeFixture(
        projDir,
        ".context-index/manifest.yaml",
        `tasks:\n  db_path: "${fakeFile}"\n`,
      );
      await assert.rejects(() => writeTasksMd(projDir), { code: "INVALID_STORAGE_PATH" });
    } finally {
      cleanupTempDir(projDir);
    }
  });

  it("CON-5: throws INVALID_STORAGE_PATH when storage root directory does not exist", async () => {
    const projDir = createTempDir();
    try {
      writeFixture(
        projDir,
        ".context-index/manifest.yaml",
        `tasks:\n  db_path: "${join(projDir, "does-not-exist")}"\n`,
      );
      await assert.rejects(() => writeTasksMd(projDir), { code: "INVALID_STORAGE_PATH" });
    } finally {
      cleanupTempDir(projDir);
    }
  });

  it("CON-6: cleanup-on-failure does not mask the underlying fs error", async () => {
    const adapter = new JsonAdapter(tmp);
    await adapter.init();
    // Inject failure by creating a directory where the final target lives,
    // making rename of a regular file impossible (EISDIR).
    const targetDir = join(tmp, ".context-index", "tasks", "tasks.md");
    mkdirSync(targetDir, { recursive: true });
    await assert.rejects(
      () => writeTasksMd(tmp),
      (err) => {
        assert.ok(err instanceof Error, "must rethrow underlying error");
        assert.ok(
          typeof err.code === "string" && err.code !== "INVALID_PROJECT_ROOT",
          `expected an fs error code, got ${err.code}`,
        );
        return true;
      },
    );
  });
});

// ─── Task 7: path containment ──────────────────────────────────────────────

describe("writeTasksMd — Task 7 path containment", () => {
  it("throws INVALID_PROJECT_ROOT when projectRoot lacks .context-index/manifest.yaml", async () => {
    const tmp = createTempDir();
    try {
      await assert.rejects(() => writeTasksMd(tmp), { code: "INVALID_PROJECT_ROOT" });
    } finally {
      cleanupTempDir(tmp);
    }
  });

  it("throws INVALID_STORAGE_PATH on crafted tasks.db_path traversal", async () => {
    const projDir = createTempDir();
    try {
      writeFixture(
        projDir,
        ".context-index/manifest.yaml",
        `tasks:\n  db_path: "/etc"\n`,
      );
      await assert.rejects(() => writeTasksMd(projDir), { code: "INVALID_STORAGE_PATH" });
    } finally {
      cleanupTempDir(projDir);
    }
  });

  it("uses public list/listEpics, not _read (SA-1 source inspection)", () => {
    // SA-1 architectural check: render-markdown.mjs source must not reach
    // into the JsonAdapter._read() private primitive. It must compose via
    // the documented public list()/listEpics() methods.
    const src = readFileSync(
      join(import.meta.dirname ?? ".", "../../../lib/issues/render-markdown.mjs"),
      "utf8",
    );
    assert.ok(!src.includes("._read("), "writeTasksMd must not call adapter._read()");
    assert.ok(src.includes(".list("), "writeTasksMd must use adapter.list()");
    assert.ok(src.includes(".listEpics("), "writeTasksMd must use adapter.listEpics()");
  });
});

// ─── Task 9: SEC-1 ─────────────────────────────────────────────────────────

describe("renderTasksMd — Task 9 SEC-1 (source `-->` defense)", () => {
  it("escapes -->` in the source slot so the HTML comment cannot close early", async () => {
    // GENERATED_HEADER(source) directly — `source` is the only attacker-controlled
    // string in this slot. We accept either escaped form `-- >` or any encoding
    // that prevents `-->` from appearing inside the rendered comment.
    const tmp = seedProject(createTempDir());
    try {
      // Inject a source containing "-->" by writing the rendered output with
      // an attacker-crafted source value via direct GENERATED_HEADER call —
      // since SEC-1's defense is at the renderer entry, we exercise both
      // public paths.
      const board = { version: 2, epics: [], issues: [] };
      // renderTasksMd hardcodes source="tasks.json" so renderTasksMd alone
      // is not directly exploitable; SEC-1 applies to the lifecycle renderMarkdown
      // and any future source-slot. We exercise the constant-equivalent
      // indirectly by checking that the rendered output's first non-blank line's
      // comment block contains no premature ` -->` token (the canonical token
      // sequence is `<!-- ... -->`).
      const out = renderTasksMd(board);
      const firstLine = out.split("\n")[0];
      const matches = firstLine.match(/-->/g) || [];
      assert.equal(matches.length, 1, "header must contain exactly one closing -->");
    } finally {
      cleanupTempDir(tmp);
    }
  });
});

// ─── Task 17: rendered-file-editing-has-no-effect ──────────────────────────

describe("writeTasksMd — Task 17 hand-edits have no effect on authoritative state", () => {
  let tmp;
  beforeEach(() => {
    tmp = seedProject(createTempDir());
  });
  afterEach(() => cleanupTempDir(tmp));

  it("hand-edit to tasks.md does not affect JsonAdapter.list(); re-render overwrites edits", async () => {
    const adapter = new JsonAdapter(tmp);
    await adapter.init();
    await adapter.create({ title: "Original", type: "task", priority: 2 });
    await writeTasksMd(tmp);
    const target = join(tmp, ".context-index", "tasks", "tasks.md");
    const before = await adapter.list();

    // Hand-edit the rendered file.
    const edited = readFileSync(target, "utf8") + "\nHACKED MARKER\n";
    writeFileSync(target, edited);
    assert.ok(readFileSync(target, "utf8").includes("HACKED MARKER"));

    // Authoritative state is unchanged.
    const after = await adapter.list();
    assert.deepEqual(after, before);

    // Re-render overwrites the hand-edit.
    await writeTasksMd(tmp);
    const reRendered = readFileSync(target, "utf8");
    assert.ok(!reRendered.includes("HACKED MARKER"), "re-render must overwrite hand-edits");
  });
});
