describe("writeTasksMd — Task 3 atomic write + CON-5 + CON-6", () => {
  let tmp;
  beforeEach(() => {
    tmp = seedProject(createTempDir());
  });
  afterEach(() => cleanupTempDir(tmp));

  it("writes <storageRoot>/.context-index/tasks/tasks.md from JsonAdapter list+listEpics", async () => {
    const adapter = new JsonAdapter(tmp);
    await adapter.init();
    await adapter.create({ title: "T1", type: "task", priority: 2 });
    await writeTasksMd(tmp);
    const out = join(tmp, ".context-index", "tasks", "tasks.md");
    assert.ok(existsSync(out), "tasks.md must exist");
    const text = readFileSync(out, "utf8");
    assert.ok(text.includes("DO NOT EDIT"), "must include generated-header");
    assert.ok(text.includes("T1"), "rendered tasks.md must include issue title");
  });

  it("CON-5: throws INVALID_STORAGE_PATH when storage root is not a directory", async () => {
    // Construct a project where tasks.db_path points to a file, not a dir.
    const projDir = createTempDir();
    try {
      writeFixture(projDir, ".context-index/manifest.yaml", "");
      const fakeFile = join(projDir, "not-a-dir");
      writeFileSync(fakeFile, "");
      writeFixture(
        projDir,
        ".context-index/manifest.yaml",
        `tasks:\n  db_path: "${fakeFile}"\n`,
      );
      await assert.rejects(() => writeTasksMd(projDir), { code: "INVALID_STORAGE_PATH" });
    } finally {
      cleanupTempDir(projDir);
    }
  });

  it("CON-5: throws INVALID_STORAGE_PATH when storage root directory does not exist", async () => {
    const projDir = createTempDir();
    try {
      writeFixture(
        projDir,
        ".context-index/manifest.yaml",
        `tasks:\n  db_path: "${join(projDir, "does-not-exist")}"\n`,
      );
      await assert.rejects(() => writeTasksMd(projDir), { code: "INVALID_STORAGE_PATH" });
    } finally {
      cleanupTempDir(projDir);
    }
  });

  it("CON-6: cleanup-on-failure does not mask the underlying fs error", async () => {
    const adapter = new JsonAdapter(tmp);
    await adapter.init();
    // Inject failure by creating a directory where the final target lives,
    // making rename of a regular file impossible (EISDIR).
    const targetDir = join(tmp, ".context-index", "tasks", "tasks.md");
    mkdirSync(targetDir, { recursive: true });
    await assert.rejects(
      () => writeTasksMd(tmp),
      (err) => {
        assert.ok(err instanceof Error, "must rethrow underlying error");
        assert.ok(
          typeof err.code === "string" && err.code !== "INVALID_PROJECT_ROOT",
          `expected an fs error code, got ${err.code}`,
        );
        return true;
      },
    );
  });
});

