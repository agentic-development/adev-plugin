// ─── SEC-3 load-time invariants ─────────────────────────────────────────────
(function assertInvariants() {
  for (const entry of MANAGED_GITIGNORE_PATHS) {
    if (typeof entry !== "object" || entry === null) {
      throw new Error("MANAGED_GITIGNORE_PATHS: each entry must be an object");
    }
    if (typeof entry.path !== "string" || entry.path.length === 0) {
      throw new Error(
        `MANAGED_GITIGNORE_PATHS: entry.path must be a non-empty string (got ${JSON.stringify(entry)})`,
      );
    }
    if (entry.comment !== undefined && typeof entry.comment !== "string") {
      throw new Error(
        `MANAGED_GITIGNORE_PATHS: entry.comment must be a string when present (got ${JSON.stringify(entry)})`,
      );
    }
    if (/[\n\r\0]/.test(entry.path)) {
      throw new Error(
        `MANAGED_GITIGNORE_PATHS: entry.path has forbidden newline/null byte: ${JSON.stringify(entry.path)}`,
      );
    }
    if (entry.comment !== undefined && /[\n\r\0]/.test(entry.comment)) {
      throw new Error(
        `MANAGED_GITIGNORE_PATHS: entry.comment has forbidden newline/null byte: ${JSON.stringify(entry.comment)}`,
      );
    }
    if (
      entry.path.includes(GITIGNORE_OPEN_MARKER) ||
      entry.path.includes(GITIGNORE_CLOSE_MARKER)
    ) {
      throw new Error(
        `MANAGED_GITIGNORE_PATHS: entry.path must not contain marker tokens: ${JSON.stringify(entry.path)}`,
      );
    }
    if (
      entry.comment !== undefined &&
      (entry.comment.includes(GITIGNORE_OPEN_MARKER) ||
        entry.comment.includes(GITIGNORE_CLOSE_MARKER))
    ) {
      throw new Error(
        `MANAGED_GITIGNORE_PATHS: entry.comment must not contain marker tokens: ${JSON.stringify(entry.comment)}`,
      );
    }
  }
})();

export default MANAGED_GITIGNORE_PATHS;
