// lib/gitignore-paths.mjs
//
// Canonical source of truth for the `adev:gitignore` managed block.
//
// MANAGED_GITIGNORE_PATHS is an ordered, frozen list of `{ path, comment? }`
// tuples consumed by:
//   - lib/gitignore-installer.mjs (renderBlock / ensureManagedBlock)
//   - tests/lib/gitignore-paths-dogfood.test.mjs (parity check against this
//     repo's own `.gitignore`)
//
// SEC-4 (non-sensitivity): entries are user-visible — they ship in committed
// `.gitignore` files. Keep them non-sensitive: no credentials, no PII, no
// host-specific paths. The list represents *categories* of ephemeral state
// that adev-managed projects must not commit; it never carries operator data.
//
// SEC-3 (load-time invariants): the IIFE below asserts at module-load time
// that no entry carries a newline / null byte or a literal marker token
// (which would otherwise break the paired-marker contract of
// lib/gitignore-installer.mjs).

const GITIGNORE_OPEN_MARKER = "# >>> adev:gitignore >>>";
const GITIGNORE_CLOSE_MARKER = "# <<< adev:gitignore <<<";

