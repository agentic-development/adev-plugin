/**
 * Markdown renderer for the JSON-backed issue board.
 *
 * Pure transformer + I/O wrapper:
 *
 *   - `renderTasksMd(board)` — pure. Consumes a parsed `tasks.json` document
 *     (`{ version, epics, issues }`) and returns the rendered `tasks.md`
 *     body. Output is round-trip-compatible with `parseTasksMd` from
 *     `lib/issues/markdown-parser.mjs`.
 *   - `writeTasksMd(projectRoot)` — composes
 *     `JsonAdapter.list()` + `JsonAdapter.listEpics()` + `renderTasksMd` and
 *     writes the result to `<storageRoot>/.context-index/tasks/tasks.md`
 *     via atomic temp-then-rename. Synchronous; the adapter's `list` and
 *     `listEpics` are awaited via a sync settled-promise extractor so the
 *     public API of `writeTasksMd` stays `void`.
 *
 * Implements the markdown-rendering-layer spec (PASS_WITH_NOTES review).
 * Source of truth always remains `tasks.json`; the rendered `tasks.md` is
 * a presentation artifact and bears a `DO NOT EDIT` header.
 *
 * Uses only Node.js built-ins: fs, path, crypto.
 *
 * @module lib/issues/render-markdown
 */

import {
  existsSync,
  mkdirSync,
  readFileSync,
  realpathSync,
  renameSync,
  statSync,
  unlinkSync,
  writeFileSync,
} from "node:fs";
import { join, resolve, sep, dirname } from "node:path";
import { randomBytes } from "node:crypto";

import { JsonAdapter } from "./json-adapter.mjs";
import { resolveStorageRoot } from "./resolve-root.mjs";
import { loadManifest } from "../manifest.mjs";

// ── Module-level constants ──────────────────────────────────────────────────

const MANIFEST_REL = join(".context-index", "manifest.yaml");
const RENDER_REL_DIR = join(".context-index", "tasks");
const RENDER_REL_FILE = join(RENDER_REL_DIR, "tasks.md");

/**
 * Per-field caps from the HTML/Markdown Escaping Contract (rule 5).
 * Exported so the lifecycle renderer (`renderMarkdown` in
 * `lib/lifecycle-state.mjs`) can consume the same caps without duplication.
 */
export const FIELD_CAPS = Object.freeze({
  title: 200,           // Issue + Epic
  next_action: 500,
  notes: 2000,          // Issue / plan-task / reviewer / validator
  branch: 255,          // git's own practical ref-name ceiling
  pr: 500,              // "#123", "org/repo#123", or a full URL
  owner: 100,           // agent / human handle recorded by `adev issues claim`
  error: 2000,          // step_failed.error
  note: 500,            // debug_intervention.note
  reason: 2000,         // manual_override.reason
  currentTask: 100,     // StateProjection label form
});

const NULL_PLACEHOLDER = "—";

// ── Error constructor ───────────────────────────────────────────────────────

function mkErr(code, msg) {
  const e = new Error(msg);
  e.code = code;
  return e;
}

// ── SEC-1 defense: strip `-->` from source slot ────────────────────────────

/**
 * Defuse a `source` string before interpolation into an HTML comment.
 *
 * Per SEC-1 in the markdown-rendering-layer review: any caller-controlled
 * string interpolated into `<!-- ... -->` must not contain `-->` or the
 * comment closes early and downstream content becomes raw HTML.
 *
 * Replaces every occurrence of `-->` with `-- >`.
 *
 * @param {string} source
 * @returns {string}
 */
export function defuseSource(source) {
  if (typeof source !== "string") return String(source ?? "");
  return source.replace(/-->/g, "-- >");
}

// ── GENERATED_HEADER ────────────────────────────────────────────────────────

/**
 * Build the canonical generated-header comment.
 *
 * `source` is defused via `defuseSource` so attacker-controlled source
 * labels cannot close the HTML comment early.
 *
 * @param {string} source - Source artifact label (e.g. "tasks.json" or "<slug>.jsonl")
 * @returns {string}
 */
export function generatedHeader(source) {
  const safe = defuseSource(source);
  return `<!-- DO NOT EDIT — generated by \`adev status --render\` from ${safe}. Edits will be lost on next regeneration. -->`;
}

// Callable export so tests can do `GENERATED_HEADER('x.jsonl')` and so
// the symbol's existence is shape-introspectable.
export const GENERATED_HEADER = generatedHeader;

// ── escapeField: 6-rule HTML/Markdown escape pipeline ──────────────────────

/**
 * Apply the 6-rule HTML/Markdown escape pipeline to a free-text field.
 *
 * Rules (applied in order):
 *   1. Newline normalization: `\r\n` and `\r` → `\n`.
 *   2. Slot-context newline collapse: `inline` slots replace `\n` → ` `;
 *      `block` slots preserve `\n`.
 *   3. HTML escape: `& < > " '` → entity form.
 *   4. Markdown structural escape: `\ ` ` | * _ [ ] ( ) #` and leading `>`.
 *   5. Length truncation: per-field cap with `…[truncated]` marker.
 *   6. Null placeholder: `null` / `undefined` / `""` → em-dash `—`.
 *
 * HTML escape MUST precede markdown escape (rule 3 then rule 4) so `<`
 * becomes `&lt;`, not `\<&lt;`.
 *
 * @param {string|null|undefined} value
 * @param {object} [opts]
 * @param {"inline"|"block"} [opts.slot="inline"]
 * @param {number} [opts.cap] - Codepoint cap. When omitted, no truncation.
 * @returns {string}
 */
export function escapeField(value, opts = {}) {
  const slot = opts.slot ?? "inline";
  const cap = typeof opts.cap === "number" ? opts.cap : null;

  // Rule 6 (pre-empts): null / undefined / "" → placeholder.
  if (value === null || value === undefined || value === "") {
    return NULL_PLACEHOLDER;
  }
  let s = String(value);

  // Rule 1: newline normalization.
  s = s.replace(/\r\n/g, "\n").replace(/\r/g, "\n");

  // Rule 2: slot-context newline collapse.
  if (slot === "inline") {
    s = s.replace(/\n/g, " ");
  }

  // Rule 3: HTML escape.
  s = s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");

  // Rule 4: Markdown structural escape. Backslash first to avoid double-escape.
  s = s
    .replace(/\\/g, "\\\\")
    .replace(/`/g, "\\`")
    .replace(/\|/g, "\\|")
    .replace(/\*/g, "\\*")
    .replace(/_/g, "\\_")
    .replace(/\[/g, "\\[")
    .replace(/\]/g, "\\]")
    .replace(/\(/g, "\\(")
    .replace(/\)/g, "\\)");
  // `#` escape — preserve `&#NNN;` HTML entity sequences produced by
  // rule 3. We escape `#` ONLY when it is not the second character of a
  // numeric HTML entity (`&#...;`). Otherwise the entity becomes
  // `&\#NNN;` which breaks downstream HTML pipelines.
  //
  // Implementation: walk the string and emit `\#` for any `#` that is not
  // immediately preceded by `&`. A single regex won't suffice because
  // overlapping consecutive `#` chars defeat lookbehind-free patterns.
  {
    let out = "";
    for (let i = 0; i < s.length; i++) {
      const ch = s[i];
      if (ch === "#" && s[i - 1] !== "&") {
        out += "\\#";
      } else {
        out += ch;
      }
    }
    s = out;
  }

  // Leading `>` only — block-quote anchor.
  if (s.startsWith(">")) {
    s = "\\" + s;
  }

  // Rule 5: length truncation (codepoint-aware via Array.from).
  if (cap !== null && cap > 0) {
    const cps = Array.from(s);
    if (cps.length > cap) {
      const marker = "…[truncated]";
      const markerCps = Array.from(marker);
      if (cap <= markerCps.length) {
        // Cap is smaller than the marker — the marker itself is truncated
        // to fit. Operators who set extremely small caps get a degraded
        // marker but the cap is still respected.
        s = markerCps.slice(0, cap).join("");
      } else {
        const keep = cap - markerCps.length;
        s = cps.slice(0, keep).join("") + marker;
      }
    }
  }

  return s;
}

// ── Board validation ────────────────────────────────────────────────────────

function validateBoardShape(board) {
  if (
    board === null ||
    typeof board !== "object" ||
    Array.isArray(board) ||
    !Array.isArray(board.epics) ||
    !Array.isArray(board.issues)
  ) {
    throw mkErr(
      "INVALID_BOARD_SHAPE",
      "board must be { version, epics: [], issues: [] }",
    );
  }
}

// ── Cell helpers ────────────────────────────────────────────────────────────

/**
 * Escape a free-text value for use inside a `tasks.md` table cell.
 *
 * Unlike the general-purpose `escapeField`, this helper emits an EMPTY
 * cell for `null` / `undefined` / `""` instead of the em-dash placeholder.
 * The round-trip partner `parseTasksMd` treats both empty and `—` cells
 * as missing values, but emitting an empty cell preserves byte-exact
 * round-trip parity for fields that started life as `null`/`undefined`
 * (the JsonAdapter normalizes `next_action: null` and `notes: ""` to those
 * representations). The em-dash form is reserved for the lifecycle
 * markdown view, where rendered files are human-only and not round-tripped.
 */
function cell(value, cap) {
  if (value === null || value === undefined || value === "") return "";
  return escapeField(value, { slot: "inline", cap });
}

/**
 * Cell for IDs / refs / timestamps / numeric fields — already constrained
 * by allowlists upstream. We still strip newlines and escape pipes to
 * preserve table structure, but we do NOT em-dash nullish values; instead
 * we emit the empty cell.
 */
function rawCell(value) {
  if (value === null || value === undefined) return "";
  return String(value)
    .replace(/\r\n/g, "\n")
    .replace(/\r/g, "\n")
    .replace(/\n/g, " ")
    .replace(/\|/g, "\\|");
}

// ── renderTasksMd ───────────────────────────────────────────────────────────

const EPIC_HEADER =
  "| ID | Title | Status | Plan-Ref | Milestone | Created | Updated |\n" +
  "|----|-------|--------|----------|-----------|---------|---------|";

const ISSUE_HEADER =
  "| ID | Title | Status | Priority | Type | Epic | Plan-Ref | Plan-Task | Spec-Ref | Deps | Notes | Next-Action | Branch | PR | Owner | Claimed-At | Created | Updated |\n" +
  "|----|-------|--------|----------|------|------|----------|-----------|----------|------|-------|-------------|--------|----|-------|------------|---------|---------|";

function renderEpicRow(e) {
  const cells = [
    rawCell(e.id),
    cell(e.title, FIELD_CAPS.title),
    rawCell(e.status),
    rawCell(e.planRef),
    rawCell(e.milestone),
    rawCell(e.created),
    rawCell(e.updated),
  ];
  return "| " + cells.join(" | ") + " |";
}

function renderIssueRow(i) {
  const cells = [
    rawCell(i.id),
    cell(i.title, FIELD_CAPS.title),
    rawCell(i.status),
    rawCell(i.priority ?? 2),
    rawCell(i.type),
    rawCell(i.epicId),
    rawCell(i.planRef),
    rawCell(i.planTask),
    rawCell(i.spec_ref),
    rawCell(Array.isArray(i.dependencies) ? i.dependencies.join(",") : ""),
    cell(i.notes ?? "", FIELD_CAPS.notes),
    cell(i.next_action ?? "", FIELD_CAPS.next_action),
    // Claim/ref columns — 1:1 with the issue. Rendered through `cell` (not
    // `rawCell`) because branch names, PR URLs, and owner handles are
    // user-supplied free text that can contain markdown-structural chars.
    cell(i.branch ?? "", FIELD_CAPS.branch),
    cell(i.pr ?? "", FIELD_CAPS.pr),
    cell(i.owner ?? "", FIELD_CAPS.owner),
    rawCell(i.claimed_at),
    rawCell(i.created),
    rawCell(i.updated),
  ];
  return "| " + cells.join(" | ") + " |";
}

/**
 * Render a parsed `tasks.json` document as a markdown body suitable for
 * writing to `.context-index/tasks/tasks.md`.
 *
 * Pure — no I/O. Output preserves the existing column layout consumed by
 * `parseTasksMd` so `parseTasksMd(renderTasksMd(board)) ≡ board` for
 * canonical shapes (legacy `planRef`+`planTask` issues are excluded from
 * the round-trip property per SA-5).
 *
 * @param {{ version: number, epics: object[], issues: object[] }} board
 * @returns {string}
 */
export function renderTasksMd(board) {
  validateBoardShape(board);

  const header = generatedHeader("tasks.json");
  const openIssues = board.issues.filter((i) => i.status !== "closed");
  const closedIssues = board.issues.filter((i) => i.status === "closed");

  const lines = [];
  lines.push(header);
  lines.push("");
  lines.push("# Issue Board");
  lines.push("");

  lines.push("## Epics");
  lines.push("");
  lines.push(EPIC_HEADER);
  for (const e of board.epics) {
    lines.push(renderEpicRow(e));
  }
  lines.push("");

  lines.push("## Issues");
  lines.push("");
  lines.push(ISSUE_HEADER);
  // Open issues first, grouped by epicId for human-readability.
  const grouped = new Map();
  const orphan = [];
  for (const i of openIssues) {
    if (i.epicId) {
      if (!grouped.has(i.epicId)) grouped.set(i.epicId, []);
      grouped.get(i.epicId).push(i);
    } else {
      orphan.push(i);
    }
  }
  for (const epicId of [...grouped.keys()].sort()) {
    for (const i of grouped.get(epicId)) {
      lines.push(renderIssueRow(i));
    }
  }
  for (const i of orphan) {
    lines.push(renderIssueRow(i));
  }
  lines.push("");

  // Closed issues collapsed under <details>.
  lines.push("<details>");
  lines.push("<summary>Closed issues</summary>");
  lines.push("");
  lines.push(ISSUE_HEADER);
  for (const i of closedIssues) {
    lines.push(renderIssueRow(i));
  }
  lines.push("");
  lines.push("</details>");
  lines.push("");

  return lines.join("\n");
}

// ── Manifest extraction (CON-5 / db_path) ──────────────────────────────────

/**
 * Read the manifest for storage-root resolution. Delegates to
 * `lib/manifest.mjs::loadManifest`. Returns the full parsed manifest, or
 * null when the manifest is missing or unparseable (preserves the prior
 * tolerant contract for `resolveStorageRoot`).
 *
 * @param {string} projectRoot - Already-resolved absolute path
 * @returns {object|null}
 */
function loadManifestForStorage(projectRoot) {
  try {
    return loadManifest(projectRoot);
  } catch {
    return null;
  }
}

// ── Project-root validation ────────────────────────────────────────────────

function assertProjectRoot(projectRoot) {
  if (!projectRoot || typeof projectRoot !== "string") {
    throw mkErr("INVALID_PROJECT_ROOT", "projectRoot must be a non-empty string");
  }
  const resolved = resolve(projectRoot);
  const manifestPath = join(resolved, MANIFEST_REL);
  if (!existsSync(manifestPath)) {
    throw mkErr(
      "INVALID_PROJECT_ROOT",
      `projectRoot "${resolved}" does not contain ${MANIFEST_REL}`,
    );
  }
  return resolved;
}

// ── Storage-root validation (CON-5) ────────────────────────────────────────

/**
 * Resolve and validate the storage root. Asserts the resolved root is a
 * real existing directory containing `.context-index/manifest.yaml`
 * (positive containment per CON-5). Throws `INVALID_STORAGE_PATH` on
 * failure.
 *
 * @param {string} projectRoot - Already-resolved absolute path
 * @returns {string}
 */
function resolveAndValidateStorageRoot(projectRoot) {
  const manifest = loadManifestForStorage(projectRoot);
  const storageRoot = resolveStorageRoot(manifest, projectRoot);

  let stat;
  try {
    stat = statSync(storageRoot);
  } catch {
    throw mkErr(
      "INVALID_STORAGE_PATH",
      `tasks.db_path must point at an existing directory (got "${storageRoot}")`,
    );
  }
  if (!stat.isDirectory()) {
    throw mkErr(
      "INVALID_STORAGE_PATH",
      `tasks.db_path must point at an existing directory (got "${storageRoot}")`,
    );
  }

  let realRoot;
  try {
    realRoot = realpathSync.native(storageRoot);
  } catch {
    throw mkErr(
      "INVALID_STORAGE_PATH",
      `Resolved storage root "${storageRoot}" cannot be canonicalized`,
    );
  }
  // Defensive: storage root must itself be an adev project — i.e. contain
  // `.context-index/manifest.yaml`. Defeats `tasks.db_path: /etc` attacks
  // even when /etc exists and is a directory.
  const sentinel = join(realRoot, ".context-index", "manifest.yaml");
  if (!existsSync(sentinel)) {
    throw mkErr(
      "INVALID_STORAGE_PATH",
      `Resolved storage root "${realRoot}" lacks .context-index/manifest.yaml; refusing to write rendered artifacts outside an adev project`,
    );
  }
  return realRoot;
}

// ── Atomic write primitive ─────────────────────────────────────────────────

/**
 * Atomic markdown write via temp-file-then-rename. Mirrors
 * `lib/build-state.mjs::atomicWriteJson`. Best-effort temp-file cleanup on
 * the failure path (CON-6) — cleanup errors are swallowed; the original
 * fs error is rethrown.
 *
 * @param {string} targetPath - Absolute target path (validated)
 * @param {string} content - Body to write
 */
function atomicWriteFile(targetPath, content) {
  const dir = dirname(targetPath);
  mkdirSync(dir, { recursive: true });

  const tmpPath = targetPath + "." + randomBytes(4).toString("hex") + ".tmp";
  writeFileSync(tmpPath, content);
  try {
    renameSync(tmpPath, targetPath);
  } catch (err) {
    // CON-6: best-effort cleanup; do NOT mask the underlying fs error.
    try {
      unlinkSync(tmpPath);
    } catch {
      /* swallow cleanup errors */
    }
    throw err;
  }
}

// ── writeTasksMd ────────────────────────────────────────────────────────────

/**
 * Compose `JsonAdapter.list` + `JsonAdapter.listEpics` + `renderTasksMd`
 * and write the result to `<storageRoot>/.context-index/tasks/tasks.md`
 * via atomic temp-then-rename.
 *
 * The adapter's `list()` / `listEpics()` are `async` for API parity with
 * FileAdapter but never `await` internal I/O, so the returned promises
 * resolve synchronously within the same microtask turn. Callers may
 * `await` the returned promise from `writeTasksMd` for symmetry; the
 * write itself completes synchronously before the microtask boundary.
 *
 * SA-1: only the public `list()` / `listEpics()` API are consumed; no
 *       `_read()` private-member access.
 *
 * Throws:
 *   - `INVALID_PROJECT_ROOT` if projectRoot lacks .context-index/manifest.yaml
 *   - `INVALID_STORAGE_PATH` on traversal or non-directory db_path (CON-5)
 *   - `MALFORMED_BOARD` from JsonAdapter._read propagation
 *   - underlying fs errors on write failures (with best-effort cleanup)
 *
 * @param {string} projectRoot
 * @returns {Promise<void>}
 */
export async function writeTasksMd(projectRoot) {
  const root = assertProjectRoot(projectRoot);
  const storageRoot = resolveAndValidateStorageRoot(root);

  // SA-1: consume the public list() / listEpics() API only.
  const adapter = new JsonAdapter(root);
  const issues = await adapter.list();
  const epics = await adapter.listEpics();
  const board = { version: 2, epics, issues };

  const rendered = renderTasksMd(board);
  const targetPath = join(storageRoot, RENDER_REL_FILE);

  // Final containment assertion (defense-in-depth): targetPath stays inside storage.
  const ctxRoot = join(storageRoot, ".context-index");
  if (!targetPath.startsWith(ctxRoot + sep)) {
    throw mkErr(
      "INVALID_STORAGE_PATH",
      `Rendered target "${targetPath}" escapes ${ctxRoot}`,
    );
  }

  atomicWriteFile(targetPath, rendered);
}

